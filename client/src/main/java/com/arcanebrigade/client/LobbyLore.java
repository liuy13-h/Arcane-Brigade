package com.arcanebrigade.client;

import com.arcanebrigade.core.HeroClass;

/**
 * 王座厅四位勇者的角色档案，内容来自《角色背景设定集》(2026-09-09)。
 *
 * 下标与职业 id 对齐（1=巫师 洛赛塔、2=战士 亚瑟、3=弓箭手 埃德蒙、4=召唤师 奈菲尔提）。
 * 纯数据类：选人卡右侧的「角色背景」滚动框与「查看详情」弹层都从这里取文。
 * 召唤师虽然暂不可招募，但档案完整，仍可查看。
 */
public final class LobbyLore {

    /** 一位勇者的完整档案 */
    public record Lore(
            String name,      // 全名，如「亚瑟 · 焰誓骑士」
            String title,     // 出身/来历，如「白鹭王旗近卫」
            String role,      // 定位，如「近战 · 坦克先锋」
            String background,// 角色背景（滚动正文）
            String personality, // 性格
            String style,     // 战斗风格
            String quote) {   // 台词
    }

    private static final Lore[] LORE = new Lore[LobbyClass.SUMMONER + 1];

    static {
        LORE[HeroClass.ARCHER] = new Lore(
                "埃德蒙 · 苍雷游侠", "苍雷游侠 · 长风氏族", "远程 · 暴击射手",
                "翠风森林的守望者一族世代以弓箭为森林站岗。埃德蒙十七岁那年在雷暴夜独自猎杀了"
                        + "一头越境的雷角兽，从此弓身缠绕着不散的雷光。魔潮吞噬森林边缘那年，他背弓入王都，"
                        + "是四人中唯一「为领地而战」的人——他要的不是荣耀，是把家园从裂隙嘴里夺回来。",
                "沉默寡言，眼神锐利；话少，箭更少——因为他从不射空。",
                "自动索敌的雷电之箭，暴击如惊雷落下；站位靠后，杀敌于百步之外。",
                "「森林教会我一件事：犹豫的箭，和没射一样。」");
        LORE[HeroClass.WARRIOR] = new Lore(
                "亚瑟 · 焰誓骑士", "白鹭王旗近卫", "近战 · 坦克先锋",
                "王国最年轻的近卫骑士，出身没落骑士家庭，凭军功一路站到国王身侧。出征前夜，他在圣坛"
                        + "以掌心按住烈焰圣剑立下「焰誓」：剑火不熄，王国不陷。他是王座厅里唯一由国王亲手点名的"
                        + "英雄，也是旅团的旗帜——所有人都默认，站在最前面的那个人必须是他。",
                "热血直率，责任感重到近乎固执；把队友的名字记得比战术还熟。",
                "持焰剑顶在队伍最前，吸引怪物围攻；剑刃过处，烈火为同伴烧出退路。",
                "「我的剑还没凉。所以退后的，应该是你们。」");
        LORE[HeroClass.WIZARD] = new Lore(
                "洛赛塔 · 蔷薇女巫", "花冠乡的女巫", "法术 · 范围爆发",
                "花冠乡的药草师孤儿，跟着隐居的老女巫长大，帽檐上的花是村里孩子们一人一朵给她戴上的。"
                        + "魔潮过境时她正外出采药，回村只余灰烬。她带着老女巫留下的魔导杖来到王座厅，不是为了复仇"
                        + "的呐喊，而是带着一种安静到让人发冷的决定——她把每一朵帽上的花，都留给了要讨还的名字。",
                "温柔爱笑，涮着嗓音哼歌；但施法时的她，连亚瑟都不敢打扰。",
                "紫蔷薇法阵大范围清怪，花海即战场；怪物越密集，她越是游刃有余。",
                "「别担心，我的花不伤人——只吃怪物哦。」");
        LORE[LobbyClass.SUMMONER] = new Lore(
                "奈菲尔提 · 缚灵召唤师", "沙海古国末代祭司", "召唤 · 辅助控场",
                "千年沙海之下的黄金古国早已没入历史，奈菲尔提是守护安卡圣符的最后一代祭司。古国预言"
                        + "记载：当西方王国燃起选将圣火之日，便是裂隙洞穿世界之时。她带着双生圣符与两位胡狼灵仆"
                        + "横穿沙漠而来，向国王献上古国的结盟——她比任何人都清楚终焉之影是什么，因为她的祖先曾"
                        + "封印过它一次。",
                "从容优雅，永远带着神秘微笑；说出的话一半是安抚，一半是预言。",
                "召唤胡狼灵撕咬敌群、束缚强敌，圣符庇护全队；是旅团看不见的第四面盾。",
                "「胡狼不吠无谓之事。它们已经闻到了，那个『影子』的味道。」");
    }

    private LobbyLore() {}

    /** 取职业 id（1..4）对应的档案；未知 id 返回 null */
    public static Lore byClass(int classId) {
        return (classId > 0 && classId < LORE.length) ? LORE[classId] : null;
    }
}
